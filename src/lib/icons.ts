/** "lucide:dumbbell" → o ícone; emoji ou valor desconhecido → null. */
export function lucideOf(value: string | null | undefined): LucideIcon | null {
  if (!value?.startsWith(ICON_PREFIX)) return null;
  return ICON_GLYPHS[value.slice(ICON_PREFIX.length)] ?? null;
}
